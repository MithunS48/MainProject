/**
 * exportPdf.js
 * ─────────────
 * PDF report generation for AquaScan.
 *
 * Two exported functions:
 *   exportPredictionReport(predictions, userInfo)  — prediction history PDF
 *   exportWaterQualityReport(status, history)       — water quality PDF
 *
 * Uses jsPDF for layout and html2canvas for chart snapshots.
 * No server round-trip needed — runs entirely in the browser.
 */

import jsPDF from "jspdf";

// ─── helpers ──────────────────────────────────────────────────────────────────

const PAGE_W   = 210;  // A4 mm
const PAGE_H   = 297;
const MARGIN   = 14;
const LINE_H   = 7;
const CONTENT_W = PAGE_W - MARGIN * 2;

function addHeader(doc, title, subtitle) {
  // Blue header bar
  doc.setFillColor(14, 165, 233);
  doc.rect(0, 0, PAGE_W, 28, "F");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.setTextColor(255, 255, 255);
  doc.text("AquaScan", MARGIN, 12);

  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.text(title, MARGIN, 20);

  doc.setFontSize(8);
  doc.setTextColor(200, 230, 255);
  doc.text(subtitle, MARGIN, 26);

  return 38; // y position after header
}

function addFooter(doc, pageNum, totalPages) {
  const y = PAGE_H - 8;
  doc.setFontSize(7);
  doc.setTextColor(160, 160, 160);
  doc.setFont("helvetica", "normal");
  doc.text(
    `Generated by AquaScan • ${new Date().toLocaleString()}`,
    MARGIN, y
  );
  doc.text(`Page ${pageNum} / ${totalPages}`, PAGE_W - MARGIN, y, { align: "right" });
  doc.setDrawColor(200, 200, 200);
  doc.line(MARGIN, y - 3, PAGE_W - MARGIN, y - 3);
}

function addSectionTitle(doc, y, text) {
  doc.setFillColor(240, 249, 255);
  doc.roundedRect(MARGIN, y, CONTENT_W, 8, 2, 2, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.setTextColor(14, 116, 144);
  doc.text(text, MARGIN + 3, y + 5.5);
  return y + 12;
}

function addRow(doc, y, label, value, shade) {
  if (shade) {
    doc.setFillColor(248, 250, 252);
    doc.rect(MARGIN, y, CONTENT_W, LINE_H, "F");
  }
  doc.setFont("helvetica", "bold");
  doc.setFontSize(8);
  doc.setTextColor(71, 85, 105);
  doc.text(label, MARGIN + 2, y + 5);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(30, 41, 59);
  doc.text(String(value ?? "—"), MARGIN + 60, y + 5);
  return y + LINE_H;
}

function checkNewPage(doc, y, needed = 20) {
  if (y + needed > PAGE_H - 16) {
    doc.addPage();
    return 16;
  }
  return y;
}

// Capture a DOM element (chart div) as PNG and embed it in the PDF
async function embedChart(doc, elementId, y, label) {
  const el = document.getElementById(elementId);
  if (!el) return y;
  try {
    const { default: html2canvas } = await import("html2canvas");
    const canvas = await html2canvas(el, {
      scale: 2, backgroundColor: "#ffffff", logging: false,
    });
    const imgData = canvas.toDataURL("image/png");
    const ratio   = canvas.height / canvas.width;
    const imgW    = CONTENT_W;
    const imgH    = Math.min(imgW * ratio, 60);

    doc.setFont("helvetica", "bold");
    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139);
    doc.text(label, MARGIN, y + 4);
    y += 7;
    doc.addImage(imgData, "PNG", MARGIN, y, imgW, imgH);
    return y + imgH + 6;
  } catch {
    return y;
  }
}

// ─── Disease colour map ───────────────────────────────────────────────────────
const DISEASE_COLORS = {
  healthy:   [34,  197, 94],
  EUS:       [239, 68,  68],
  gill:      [59,  130, 246],
  red_spot:  [249, 115, 22],
};

// ─── Prediction history PDF ───────────────────────────────────────────────────

export async function exportPredictionReport(predictions, userInfo = {}) {
  const doc  = new jsPDF({ unit: "mm", format: "a4" });
  const date = new Date().toLocaleDateString();

  let y = addHeader(
    doc,
    "Fish Disease Prediction Report",
    `Farmer: ${userInfo.full_name || "—"}  •  Email: ${userInfo.email || "—"}  •  Date: ${date}`
  );

  // ── Summary stats ─────────────────────────────────────────────────────────
  y = addSectionTitle(doc, y, "Summary");

  const total     = predictions.length;
  const healthy   = predictions.filter(p => p.predicted_class === "healthy").length;
  const diseased  = total - healthy;
  const avgConf   = total
    ? (predictions.reduce((s, p) => s + (p.confidence_pct || 0), 0) / total).toFixed(1)
    : "—";

  const summaryRows = [
    ["Total analyses",        total],
    ["Healthy",               healthy],
    ["Disease detected",      diseased],
    ["Average confidence",    `${avgConf}%`],
  ];
  summaryRows.forEach(([l, v], i) => {
    y = addRow(doc, y, l, v, i % 2 === 0);
  });

  y += 6;

  // Disease breakdown
  const breakdown = {};
  predictions.forEach(p => {
    breakdown[p.predicted_class] = (breakdown[p.predicted_class] || 0) + 1;
  });
  y = addSectionTitle(doc, y, "Disease Breakdown");
  Object.entries(breakdown).forEach(([cls, cnt], i) => {
    y = addRow(doc, y, cls, `${cnt} (${((cnt/total)*100).toFixed(1)}%)`, i % 2 === 0);
  });

  y += 6;

  // ── Individual predictions ─────────────────────────────────────────────────
  y = addSectionTitle(doc, y, "All Predictions");

  const colW = [8, 50, 30, 30, 40];
  const headers = ["#", "Diagnosis", "Confidence", "Date", "File"];

  // Table header
  doc.setFillColor(14, 165, 233);
  doc.rect(MARGIN, y, CONTENT_W, 8, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(7.5);
  doc.setTextColor(255, 255, 255);
  let cx = MARGIN + 2;
  headers.forEach((h, i) => { doc.text(h, cx, y + 5.5); cx += colW[i]; });
  y += 8;

  predictions.forEach((p, idx) => {
    y = checkNewPage(doc, y, 9);
    const shade = idx % 2 === 0;
    if (shade) { doc.setFillColor(248, 250, 252); doc.rect(MARGIN, y, CONTENT_W, 8, "F"); }

    const [r, g, b] = DISEASE_COLORS[p.predicted_class] || [100, 100, 100];
    const cols = [
      String(idx + 1),
      p.predicted_label || p.predicted_class,
      `${p.confidence_pct?.toFixed(1) ?? "—"}%`,
      p.created_at ? new Date(p.created_at).toLocaleDateString() : "—",
      (p.original_filename || "").substring(0, 22),
    ];

    cx = MARGIN + 2;
    cols.forEach((text, i) => {
      if (i === 1) {
        doc.setTextColor(r, g, b);
        doc.setFont("helvetica", "bold");
      } else {
        doc.setTextColor(50, 50, 50);
        doc.setFont("helvetica", "normal");
      }
      doc.setFontSize(7.5);
      doc.text(text, cx, y + 5.5);
      cx += colW[i];
    });
    y += 8;
  });

  // ── Footer on all pages ────────────────────────────────────────────────────
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    addFooter(doc, i, totalPages);
  }

  doc.save(`AquaScan_Predictions_${date.replace(/\//g, "-")}.pdf`);
}


// ─── Water quality PDF ────────────────────────────────────────────────────────

export async function exportWaterQualityReport(status, history = [], userInfo = {}) {
  const doc  = new jsPDF({ unit: "mm", format: "a4" });
  const date = new Date().toLocaleDateString();
  const r    = status?.latest;

  let y = addHeader(
    doc,
    `Water Quality Report — ${status?.device_id ?? "Unknown Device"}`,
    `Farmer: ${userInfo.full_name || "—"}  •  Generated: ${date}`
  );

  // ── Device info ──────────────────────────────────────────────────────────
  y = addSectionTitle(doc, y, "Device Information");
  const deviceRows = [
    ["Device ID",    status?.device_id],
    ["Label",        status?.label || "—"],
    ["Status",       status?.online ? "Online" : "Offline"],
    ["Last seen",    status?.last_seen ? new Date(status.last_seen).toLocaleString() : "—"],
    ["pH threshold", `${status?.ph_min} – ${status?.ph_max}`],
    ["Temp threshold", `${status?.temp_min} – ${status?.temp_max} °C`],
  ];
  deviceRows.forEach(([l, v], i) => { y = addRow(doc, y, l, v, i % 2 === 0); });

  y += 6;

  // ── Latest reading ────────────────────────────────────────────────────────
  if (r) {
    y = addSectionTitle(doc, y, "Latest Reading");
    const readingRows = [
      ["pH",                  r.ph?.toFixed(3)],
      ["pH status",           r.ph_status],
      ["Temperature",         `${r.temperature?.toFixed(2)} °C`],
      ["Temperature status",  r.temp_status],
      ["[H⁺] concentration",  `${r.h_ion_conc?.toExponential(3)} mol/L`],
      ["pOH (≈25 °C)",        r.poh?.toFixed(3)],
      ["Received at",         r.received_at ? new Date(r.received_at).toLocaleString() : "—"],
    ];
    readingRows.forEach(([l, v], i) => { y = addRow(doc, y, l, v, i % 2 === 0); });

    if (r.alerts?.length) {
      y += 4;
      y = addSectionTitle(doc, y, `Alerts (${r.alerts.length})`);
      r.alerts.forEach((a, i) => {
        y = checkNewPage(doc, y, 8);
        doc.setFillColor(255, 251, 235);
        doc.rect(MARGIN, y, CONTENT_W, 7, "F");
        doc.setFont("helvetica", "normal");
        doc.setFontSize(8);
        doc.setTextColor(180, 83, 9);
        doc.text(`• ${a}`, MARGIN + 3, y + 5);
        y += 7;
      });
    }
  }

  y += 6;

  // ── Historical readings table ──────────────────────────────────────────────
  if (history.length > 0) {
    y = checkNewPage(doc, y, 30);
    y = addSectionTitle(doc, y, `Reading History (${history.length} records)`);

    const hColW = [12, 28, 28, 28, 60];
    const hHdr  = ["#", "pH", "Temp °C", "pH Status", "Timestamp"];

    doc.setFillColor(14, 165, 233);
    doc.rect(MARGIN, y, CONTENT_W, 8, "F");
    doc.setFont("helvetica", "bold");
    doc.setFontSize(7.5);
    doc.setTextColor(255, 255, 255);
    let cx = MARGIN + 2;
    hHdr.forEach((h, i) => { doc.text(h, cx, y + 5.5); cx += hColW[i]; });
    y += 8;

    // Show last 50 rows max to keep file size reasonable
    const rows = [...history].slice(0, 50);
    rows.forEach((row, idx) => {
      y = checkNewPage(doc, y, 8);
      if (idx % 2 === 0) {
        doc.setFillColor(248, 250, 252);
        doc.rect(MARGIN, y, CONTENT_W, 7, "F");
      }
      const cols = [
        String(idx + 1),
        row.ph?.toFixed(2) ?? "—",
        row.temperature?.toFixed(1) ?? "—",
        row.ph_status ?? "—",
        row.received_at ? new Date(row.received_at).toLocaleString() : "—",
      ];
      cx = MARGIN + 2;
      cols.forEach((text, i) => {
        doc.setFont("helvetica", "normal");
        doc.setFontSize(7.5);
        doc.setTextColor(50, 50, 50);
        doc.text(text, cx, y + 5);
        cx += hColW[i];
      });
      y += 7;
    });
  }

  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    addFooter(doc, i, totalPages);
  }

  doc.save(`AquaScan_WaterQuality_${status?.device_id ?? "report"}_${date.replace(/\//g, "-")}.pdf`);
}
